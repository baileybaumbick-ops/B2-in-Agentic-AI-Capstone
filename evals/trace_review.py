"""Trace one real review through every stage, plus one failed/ambiguous case (no model calls).

    python evals/trace_review.py --run-dir runs/full      -> docs/TRACE.md

Chooses a review that is in the memo evidence pack (so it reaches a memo claim), preferring one that the
independent verifier also sampled and that belongs to the top-ranked issue.
"""
import argparse
import csv
import gzip
import json
import re
import sqlite3
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))


def jl(path):
    p = Path(path)
    if not p.exists():
        return []
    op = gzip.open if p.suffix == ".gz" else open
    with op(p, "rt", encoding="utf-8") as f:
        return [json.loads(l) for l in f if l.strip()]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--run-dir", required=True)
    ap.add_argument("--out", default=str(ROOT / "docs" / "TRACE.md"))
    a = ap.parse_args()
    rd = Path(a.run_dir)
    db = sqlite3.connect(rd / "state.sqlite")
    recs = {r["review_id"]: r for r in jl(rd / "enriched.jsonl.gz")}
    ver = {r["review_id"]: r for r in jl(rd / "verify" / "verifier_predictions.jsonl")}
    member = {r["review_id"]: r["issue_id"] for r in csv.DictReader(open(rd / "group" / "membership.csv", encoding="utf-8"))}
    ranking = list(csv.DictReader(open(rd / "rank" / "ranking.csv", encoding="utf-8")))
    rank_by = {r["issue_id"]: r for r in ranking}
    pack = json.load(open(rd / "memo" / "memo_input_pack.json", encoding="utf-8"))
    memo = json.load(open(rd / "memo" / "memo_output.json", encoding="utf-8"))
    claims = {c["claim_id"]: c for c in json.load(open(rd / "memo" / "claims_all.json", encoding="utf-8"))}
    body = memo["memo"]["body_markdown"]
    evidence = [(i["issue_id"], e["review_id"]) for i in pack["issues"] for e in i["examples"]]
    top = ranking[0]["issue_id"]

    def score(item):
        iid, rid = item
        return (rid in body, rid in ver, iid == top, -int(rank_by[iid]["rank"]))
    iid, rid = max(evidence, key=score)
    r = recs[rid]
    src = db.execute("SELECT row_idx, review_rating, review_likes, app_version, review_timestamp, review_text, row_sha "
                     "FROM source WHERE review_id=?", (rid,)).fetchone()
    origin = r.get("cache_source_id") or rid
    call_id = recs[origin].get("enrich_request_id")
    call = next((c for c in jl(rd / "calls.jsonl") if c["request_id"] == call_id), {})
    issue = next(i for i in json.load(open(rd / "group" / "issues.json", encoding="utf-8"))["issues"] if i["issue_id"] == iid)
    cited_claims = [c for cid, c in claims.items() if c.get("issue_id") == iid and f"[{cid}]" in body]
    text = src[5]
    L = [f"# One real review traced end to end (`{rd.name}`)", "",
         "Generated by `python evals/trace_review.py --run-dir " + str(rd).replace("\\", "/") + "` from saved artifacts only (no model calls).", "",
         "## 1. Source row (ingest, code)", "",
         f"- review_id `{rid}` (source row {src[0]}), rating {src[1]}, likes {src[2]}, app_version `{src[3] or '(missing)'}`, timestamp {src[4]}",
         f"- row SHA-256 `{src[6]}`", f"- text ({len(text)} chars): \"{text[:400]}{'...' if len(text) > 400 else ''}\"", "",
         "## 2. Enrichment (ENRICHER role)", "",
         f"- request `{call_id}` - model `{call.get('model')}`, tier `{call.get('service_tier')}`, phase `{call.get('phase')}`, "
         f"{len(call.get('review_ids', []))} reviews in the batch, {call.get('input_tokens')} input tokens "
         f"({call.get('cached_tokens')} cached), {call.get('output_tokens')} output tokens, cost ${call.get('cost_usd')}",
         f"- label_config `{r['label_config']}`" + (f"; reused from exact-text original `{origin}` (cache_source_id)" if origin != rid else ""),
         f"- labels: topic **{r['topic']}**, subtopic **{r.get('subtopic')}**, intent **{r['intent']}**, severity **{r['severity']}**, "
         f"sentiment {r['sentiment']}, entities {r['entities']}, needs_review {r['needs_review']}",
         f"- evidence_quote: \"{r['evidence_quote']}\" (exact substring: {r['evidence_quote'] in text})", "",
         "## 3. Independent verification (VERIFIER role)", ""]
    if rid in ver:
        v = ver[rid]
        L.append(f"- Jev re-labeled it from the text only (request `{v['request_id']}`): topic {v['topic']}, subtopic {v['subtopic']}, "
                 f"intent {v['intent']}, severity {v['severity']}, confidence {v.get('confidence')}")
        L.append(f"- agreement: topic {v['topic'] == r['topic']}, intent {v['intent'] == r['intent']}, severity {v['severity'] == r['severity']}")
    else:
        L.append("- Not in the seeded verification sample (the verifier re-labels a declared random 0.4% sample).")
    row = rank_by[iid]
    L += ["", "## 4. Issue membership (code) and naming (GROUPER role)", "",
          f"- membership.csv: `{iid},{rid}` (rule: issue_id = topic.subtopic for every completed complaint/cancellation)",
          f"- issue name (model, from {len(issue['sample_review_ids'])} sampled quotes): \"{issue.get('name')}\"; coherence {issue.get('coherence')}", "",
          "## 5. Ranking (code)", "",
          f"- ranking.csv row: rank {row['rank']}, complaint_count {row['complaint_count']}, severity_sum {row['severity_sum']}, "
          f"mean_severity {row['mean_severity']}, priority_score {row['priority_score']}", "",
          "## 6. Memo claim (MEMO role, checked by code)", "",
          f"- the review is in the memo evidence pack for `{iid}`; cited in the memo text: {rid in body}"]
    for c in cited_claims:
        if c["metric"] in ("complaint_count", "severity_sum", "mean_severity", "priority_score"):
            check = f"matches ranking.csv: {str(c['value']) == row[c['metric']]}"
        else:
            check = "context number from rank/aggregates.csv (not a baseline metric)"
        L.append(f"- claim `{c['claim_id']}`: {c['metric']} = {c['display']} ({check})")
    for m in re.finditer(r"[^.\n]*\[(?:" + "|".join(c["claim_id"] for c in cited_claims) + r")\][^.\n]*\.", body) if cited_claims else []:
        L.append(f"- memo sentence: \"{m.group(0).strip()}\"")
        break
    # failed / ambiguous case
    L += ["", "## A failed or ambiguous case and its handling", ""]
    q = db.execute("SELECT r.review_id, r.reason, r.attempts, s.review_text FROM records r JOIN source s USING(review_id) "
                   "WHERE r.status='quarantined' AND r.reason != 'empty_review_text' LIMIT 1").fetchone()
    fb = db.execute("SELECT r.review_id, r.label_config, r.attempts, s.review_text, r.topic, r.intent, r.severity FROM records r "
                    "JOIN source s USING(review_id) WHERE r.label_config LIKE '%fallback%' OR r.label_config LIKE 'jev%' LIMIT 1").fetchone()
    if fb:
        L.append(f"- Recovered by fallback: `{fb[0]}` (attempts {fb[2]}), text \"{fb[3][:200]}\" -> {fb[4]}/{fb[5]}/severity {fb[6]} "
                 f"under `{fb[1]}` after the primary enricher's output failed validation or was refused.")
    if q:
        L.append(f"- Still quarantined: `{q[0]}`, reason `{q[1]}`, attempts {q[2]}, text \"{q[3][:200]}\". It is excluded from "
                 "aggregates and counted as an incomplete classification.")
    dis = list(csv.DictReader(open(rd / "verify" / "disagreements.csv", encoding="utf-8")))
    if dis:
        d = dis[0]
        t = db.execute("SELECT review_text FROM source WHERE review_id=?", (d["review_id"],)).fetchone()[0]
        L.append(f"- Ambiguous (enricher vs verifier disagree): `{d['review_id']}` \"{t[:200]}\" - enricher "
                 f"{d['enrich_topic']}/{d['enrich_intent']}/sev {d['enrich_severity']} vs verifier {d['verify_topic']}/"
                 f"{d['verify_intent']}/sev {d['verify_severity']}. Handling: the enricher label stands in aggregates; the "
                 "disagreement is reported in verify/disagreements.csv and counted in the verifier agreement rates.")
    Path(a.out).write_text("\n".join(L) + "\n", encoding="utf-8")
    print("wrote", a.out, "traced", rid, "issue", iid)


if __name__ == "__main__":
    main()
